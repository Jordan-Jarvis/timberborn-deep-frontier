// Late-game buildings: promote reviewed studies into the active package.
//
// For each building listed in tools/lategame_batches.json this replaces the
// old 3×3 prototype geometry with the study's own registration
// (outputs/lategame-studies/<id>-registration.json, written by
// render_lategame_studies.py) and copies its official Timbermesh export from
// outputs/lategame-integration/Data (export_lategame_models.py).
//
// Grid contract:
// - Occupied cells come from the authored parts; they are solid ('All') and
//   ground cells need ground or a platform below. Everything else is free.
// - The native Entrance is the path cell in front of the first ground door
//   (vanilla convention); its doorstep must be a building cell.
// - Shafts may meet any authored solid wall (solidPowerFaces limited to the
//   registration's wallFaces), except toward the door. This list only orders
//   the authored sockets: connection_content.mjs replaces the final face set
//   with every measured flat exterior face (outputs/connection-faces).
// - The vanilla template's construction base is replaced by the study's own
//   construction stage, sized to the new footprint.
// - Template navmesh edges describe the template's interior and are rejected.
// - A building with UnderstructureConstraintSpec declares the ground core that
//   stands over its map marker (see understructureCore below).
import {copyFile, mkdir, readFile, writeFile} from 'node:fs/promises';
import {dirname, sep} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {applyNativeBuildingAssembly} from './native_building_content.mjs';
import {solidPowerFaces} from './power_faces.mjs';
import {applyVanillaSmoke} from './vanilla_smoke.mjs';

const root = new URL('../', import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const xyz = ([X, Y, Z]) => ({X, Y, Z});
const MAX_DOOR_OFFSET = .25;

export const LATEGAME = new Set((await read('tools/lategame_batches.json')).integrated);
// Registered cells over flat roofs that hold nothing (tools/roof_decks.json freedAbove,
// generated by roof_deck_content.mjs): left unoccupied so the roof below is platformable.
const FREED_ABOVE = (await read('tools/roof_decks.json')).freedAbove;

export function lategameBlocks(registration) {
  const [w, h] = registration.footprint, layers = registration.height;
  const occupied = new Set(registration.occupied.map((c) => c.join(',')));
  const blocks = [];
  for (let z = 0; z < layers; z++) for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const solid = occupied.has([x, y, z].join(','));
    blocks.push({MatterBelow: solid && z === 0 ? 'GroundOrStackable' : 'Any', Occupations: solid ? 'All' : 'None',
      Stackable: 'None', OccupyAllBelow: false, Underground: false});
  }
  return blocks;
}

// Shafts only meet faces that authored walls actually close (the
// registration's wallFaces), plus the ground layer's Bottom faces.
export function wallTransputs(transputs, registration) {
  if (!Array.isArray(registration.wallFaces)) throw new Error(`${registration.ident}: registration has no wallFaces; rebuild the study`);
  const walls = new Set(registration.wallFaces.map((f) => f.join(',')));
  return transputs.map((t) => {
    const {X, Y, Z} = t.Coordinates;
    const directions = t.Directions.split(', ').filter((d) => d === 'Bottom' || walls.has([X, Y, Z, d].join(',')));
    return {...t, Directions: directions.join(', ')};
  }).filter((t) => t.Directions);
}

// Solid cells merged into few boxes: greedy rectangles per layer, then stacked
// where consecutive layers repeat the same rectangle. Covers exactly the 'All'
// cells (native collider axes: Y is height).
export function lategameColliders(blocks, [w, h, layers]) {
  const solid = (x, y, z) => blocks[(z * h + y) * w + x].Occupations === 'All';
  const open = new Map();
  const boxes = [];
  const close = (key) => {
    const [x0, y0, x1, y1] = key.split(',').map(Number), {z0, z1} = open.get(key);
    boxes.push({Center: {X: (x0 + x1 + 1) / 2, Y: (z0 + z1 + 1) / 2, Z: (y0 + y1 + 1) / 2},
      Size: {X: x1 - x0 + 1, Y: z1 - z0 + 1, Z: y1 - y0 + 1}});
    open.delete(key);
  };
  for (let z = 0; z < layers; z++) {
    const used = new Set(), rects = [];
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (!solid(x, y, z) || used.has(x + ',' + y)) continue;
      let x1 = x;
      while (x1 + 1 < w && solid(x1 + 1, y, z) && !used.has(x1 + 1 + ',' + y)) x1++;
      let y1 = y;
      const rowFree = (yy) => { for (let xx = x; xx <= x1; xx++) if (!solid(xx, yy, z) || used.has(xx + ',' + yy)) return false; return true; };
      while (y1 + 1 < h && rowFree(y1 + 1)) y1++;
      for (let yy = y; yy <= y1; yy++) for (let xx = x; xx <= x1; xx++) used.add(xx + ',' + yy);
      rects.push([x, y, x1, y1].join(','));
    }
    for (const key of [...open.keys()]) if (!rects.includes(key)) close(key);
    for (const key of rects) if (open.has(key)) open.get(key).z1 = z; else open.set(key, {z0: z, z1: z});
  }
  for (const key of [...open.keys()]) close(key);
  return {BoxColliders: boxes, SphereColliders: [], CapsuleColliders: []};
}

// Understructure core (Timberborn 1.1 UnderstructureFinder.FindStrict): every
// foundation block (solid MatterBelow) whose occupation is exactly Top,
// Corners or Top|Corners must find the same named understructure entity in
// its cell. The marker (DeepOreVein, cloned from UndergroundRuins) fills
// Floor|Bottom|Corners|Path|Middle of its ground cells, so over the marker the
// building may claim only Top. `core` = [x0, y0, x1, y1] is that ground
// rectangle and must match the marker's size: its solid cells become Top on
// Ground (vanilla EfficientMine), its empty cells stay free. Solid cells
// elsewhere stay 'All', which the finder ignores.
export function understructureCore(blocks, [w, h], {core, size}, door, id) {
  const [x0, y0, x1, y1] = core;
  if (!(x0 >= 0 && y0 >= 0 && x1 < w && y1 < h && x0 <= x1 && y0 <= y1)) throw new Error(`${id}: understructure core ${core} lies outside the ${w}×${h} footprint`);
  if (x1 - x0 + 1 !== size[0] || y1 - y0 + 1 !== size[1]) throw new Error(`${id}: understructure core ${core} does not match the ${size.join('×')} marker`);
  for (const [x, y, z] of [door.doorstep, door.entrance]) {
    if (z === 0 && x >= x0 && x <= x1 && y >= y0 && y <= y1) throw new Error(`${id}: door cell ${[x, y, z]} lies over the understructure`);
  }
  let cells = 0;
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
    const block = blocks[y * w + x];
    if (block.Occupations === 'None') continue;
    Object.assign(block, {MatterBelow: 'Ground', Occupations: 'Top'});
    cells++;
  }
  if (cells === 0) throw new Error(`${id}: understructure core ${core} has no building cell`);
  return cells;
}

// Roof terrace (player paths on an authored deck, as on the Grocery balcony):
// each listed cell is free and its support cell directly below is solid; the
// support becomes Stackable BlockObject so native paths and platforms rest on it.
export function roofTerrace(blocks, [w, h, layers], cells, id) {
  if (!Array.isArray(cells) || !cells.length) throw new Error(`${id}: roof terrace needs at least one cell`);
  const inside = ([x, y, z]) => x >= 0 && y >= 0 && z >= 0 && x < w && y < h && z < layers;
  const block = ([x, y, z]) => blocks[(z * h + y) * w + x];
  for (const [x, y, z] of cells) {
    if (!inside([x, y, z]) || z < 1) throw new Error(`${id}: terrace cell ${[x, y, z]} lies outside the building or on the ground layer`);
    if (block([x, y, z]).Occupations !== 'None') throw new Error(`${id}: terrace cell ${[x, y, z]} is occupied`);
    const support = block([x, y, z - 1]);
    if (support.Occupations !== 'All') throw new Error(`${id}: terrace cell ${[x, y, z]} has no solid support below`);
    support.Stackable = 'BlockObject';
  }
  return cells.length;
}

// Purposeful overhangs: occupied ground-layer cells that must stand over open
// space (a native intake pipe column), MatterBelow Air as on the vanilla Deep
// Badwater Pump's intake cell. Every other ground cell keeps GroundOrStackable.
export function groundOverhangs(blocks, [w, h], cells, door, id) {
  if (!Array.isArray(cells) || !cells.length) throw new Error(`${id}: overhangs need at least one cell`);
  for (const [x, y, z] of cells) {
    if (z !== 0 || x < 0 || y < 0 || x >= w || y >= h) throw new Error(`${id}: overhang ${[x, y, z]} must be a ground-layer cell of the footprint`);
    if ([door.doorstep, door.entrance].some((c) => c.join() === [x, y, z].join())) throw new Error(`${id}: overhang ${[x, y, z]} is a door cell`);
    const block = blocks[y * w + x];
    if (block.Occupations !== 'All') throw new Error(`${id}: overhang ${[x, y, z]} is not a building cell`);
    block.MatterBelow = 'Air';
  }
  return cells.length;
}

export async function lategameBlueprint(value, id, {understructure, terrace, overhangs} = {}) {
  if (!LATEGAME.has(id)) throw new Error('Not an integrated late-game building: ' + id);
  if (Boolean(understructure) !== Boolean(value.UnderstructureConstraintSpec)) {
    throw new Error(`${id}: an understructure core and UnderstructureConstraintSpec must be declared together`);
  }
  const nav = value.BlockObjectNavMeshSettingsSpec;
  if (nav && (nav.EdgeGroups.length || nav.UnblockedCoordinates.length || nav.BlockedEdges.length)) {
    throw new Error(`${id}: template navmesh edges describe the template interior; remove them at the source`);
  }
  const registration = await read(`outputs/lategame-studies/${id}-registration.json`);
  if (registration.ident !== id) throw new Error('Registration identity mismatch: ' + id);
  const [w, h] = registration.footprint, layers = registration.height;
  const size = [w, h, layers];
  const blocks = lategameBlocks(registration);
  const index = ([x, y, z]) => (z * h + y) * w + x;
  for (const [x, y, z] of FREED_ABOVE[id] ?? []) {
    const b = blocks[index([x, y, z])];
    if (z < 1 || z >= layers || b.Occupations !== 'All' || blocks[index([x, y, z - 1])].Occupations !== 'All')
      throw new Error(`${id}: freed roof cell ${[x, y, z]} is not a registered cell over a solid roof cell`);
    Object.assign(b, {MatterBelow: 'Any', Occupations: 'None', Stackable: 'None'});
  }
  const inside = ([x, y, z]) => x >= 0 && y >= 0 && z >= 0 && x < w && y < h && z < layers;
  const door = registration.doors.find((d) => d.position[2] === 0);
  if (!door) throw new Error(id + ': no ground door registered');
  if (door.faceOffset > MAX_DOOR_OFFSET) throw new Error(`${id}: door face sits ${door.faceOffset} tiles behind its cell edge`);
  if (!inside(door.doorstep) || blocks[index(door.doorstep)].Occupations !== 'All') throw new Error(`${id}: doorstep ${door.doorstep} is not a building cell`);
  if (inside(door.entrance) && blocks[index(door.entrance)].Occupations !== 'None') throw new Error(`${id}: entrance path cell ${door.entrance} is occupied`);

  value.BlockObjectSpec = {Size: xyz(size), Blocks: blocks, Entrance: {HasEntrance: true, Coordinates: xyz(door.entrance)},
    BaseZ: 0, Overridable: false, Flippable: true};
  const [dx, dy, dz] = door.position;
  value.BuildingAccessibleSpec = {...value.BuildingAccessibleSpec, LocalAccess: xyz([dx, dz, dy]), ForceOneFinalAccess: false};
  if (value.MechanicalNodeSpec) {
    value.TransputProviderSpec = {IgnoreRotation: false,
      Transputs: wallTransputs(solidPowerFaces(blocks, size, {exclude: [door.entrance, door.doorstep]}), registration)};
  }
  const model = value.Children['#Finished'].TimbermeshSpec.Model;
  if (!model.endsWith(`/${id}.IronTeeth.Model`)) throw new Error(`${id}: unexpected model path ${model}`);
  const stage = model.replace(/\.Model$/, '.ConstructionStage0.Model');
  const colliders = lategameColliders(blocks, size);
  value.Children['#Finished'].CollidersSpec = colliders;
  value.Children['#Unfinished'] = {Children: {ConstructionStage0: {TimbermeshSpec: {Model: stage}, CollidersSpec: colliders}}};
  // One construction stage and no base: no intermediate thresholds.
  value.ConstructionSiteProgressVisualizerSpec = {ProgressThresholds: []};
  // Workers idle at the doorway through native slots in the exported model.
  if (value.WorkplaceSpec) {
    value.WorkplaceSlotManagerSpec = {};
    value.WorkshopWorkerHiderSpec = {};
    value.TransformSlotInitializerSpec = {Slots: [{SlotKeyword: 'Entrance', Animation: 'ForcedIdle', Inanimate: false,
      RandomizeYRotation: false, WaterSlot: false}]};
  }
  // Shafts and colliders above follow the solid cells; only the occupation
  // over the marker narrows to Top.
  const understructureCells = understructure ? understructureCore(blocks, size, understructure, door, id) : 0;
  const terraceCells = terrace ? roofTerrace(blocks, size, terrace, id) : 0;
  const overhangCells = overhangs ? groundOverhangs(blocks, size, overhangs, door, id) : 0;
  // Every study animates its machinery. Workshops run it with the native
  // controller (moving while they work); native good-powered generators with
  // the native GoodPoweredGeneratorAnimator their Steam Engine template
  // carries (moving while the output multiplier is above zero); other
  // buildings play it ambiently.
  if (value.WorkshopSpec) value.WorkshopAnimationControllerSpec = {};
  else if (value.GoodPoweredGeneratorSpec) {
    if (!value.GoodPoweredGeneratorAnimatorSpec) throw new Error(`${id}: a good-powered generator needs the native GoodPoweredGeneratorAnimatorSpec`);
  }
  else value.AmbientAnimationSpec = {};
  // Vanilla smoke/steam at the study's flue mouths (registration smokeEmitters).
  const smoke = applyVanillaSmoke(value, registration, id);
  await applyNativeBuildingAssembly(value, id, [0, 0, 0], {goodId: 'Water', flowNodes: [], wheelNodes: []});
  return {size, entrance: door.entrance, doorstep: door.doorstep, model, stage, understructureCells, terraceCells, overhangCells, smoke};
}

// Values recorded in a late-game study module (tools/asset-pipeline/
// lategame_<Id>.py) as single-line Python literals.
const DIRECTION_STEPS = {Left: [-1, 0, 0], Right: [1, 0, 0], Down: [0, -1, 0], Up: [0, 1, 0]};
async function studySource(id) {
  return readFile(new URL(`tools/asset-pipeline/lategame_${id}.py`, root), 'utf8');
}
// NAME = {'cell': [x, y, z], ...}: the recorded block cell.
export async function studyCell(id, constant) {
  const m = (await studySource(id)).match(new RegExp(`^${constant} = \\{'cell': \\[(\\d+), (\\d+), (\\d+)\\]`, 'm'));
  if (!m) throw new Error(`lategame_${id}.py: ${constant} cell not found`);
  return [+m[1], +m[2], +m[3]];
}
// NAME = 'Value': a recorded string constant.
export async function studyString(id, constant) {
  const m = (await studySource(id)).match(new RegExp(`^${constant} = '(\\w+)'$`, 'm'));
  if (!m) throw new Error(`lategame_${id}.py: ${constant} not found`);
  return m[1];
}
// Timber Pipes port from a socket record {'cell', 'direction', 'state', ...}.
// The socket is an occupied building cell whose outward cell (the pipe) is free.
export async function studyPipePort(id, constant) {
  const m = (await studySource(id)).match(new RegExp(`^${constant} = \\{'cell': \\[(\\d+), (\\d+), (\\d+)\\], 'direction': '(\\w+)', 'state': '(\\w+)'`, 'm'));
  if (!m) throw new Error(`lategame_${id}.py: ${constant} socket not found`);
  const registration = await read(`outputs/lategame-studies/${id}-registration.json`);
  const occupied = new Set(registration.occupied.map((c) => c.join(',')));
  const cell = [+m[1], +m[2], +m[3]], step = DIRECTION_STEPS[m[4]];
  if (!step || !occupied.has(cell.join(',')) || occupied.has(cell.map((v, i) => v + step[i]).join(',')))
    throw new Error(`${id}: ${constant} ${cell} ${m[4]} is not an occupied cell facing a free one`);
  if (!['OpenIn', 'OpenOut', 'Open'].includes(m[5])) throw new Error(`${id}: ${constant} state ${m[5]} is not a Timber Pipes port state`);
  return {Coordinates: xyz(cell), Directions: m[4], State: m[5]};
}

// Native props whose shipped model uses materials outside the vanilla Iron
// Teeth and Common collections (the Folktails Fountain of Joy on the Town
// Plaza). The game resolves a prop model's materials through the player's
// faction collections, so these are registered for Iron Teeth explicitly, as
// civic_building_content.mjs registers the Folktails flowers. A prop model in
// a late-game assembly that needs materials not listed here fails
// validate_model_bindings.py; add it here.
const NATIVE_PROP_MATERIALS = {
  'FountainOfJoy.Folktails': [
    'Materials/UberAtlas/Materials/Folktails/BaseMetal.Folktails',
    'Materials/UberAtlas/Materials/Folktails/BaseWood_LightBrown.Folktails',
    'Materials/UberAtlas/Materials/Folktails/BaseWood_White.Folktails',
    'Materials/UberAtlas/Materials/Folktails/IrregularPlanks_Brown.Folktails',
    'Buildings/Monuments/FountainOfJoy/FountainWater',
  ],
};

// One Iron Teeth material collection for every late-game assembly's props
// (BaseWood_Brown.Folktails, also used by the fountain, is registered by the
// civic collection). Rewritten whole on every call, so it never drifts.
async function writeNativePropMaterials(targetRoot) {
  const materials = new Set();
  for (const id of LATEGAME) {
    const assembly = await read(`outputs/reference-studies/${id}-native-assembly.json`);
    for (const prop of assembly.props) for (const m of NATIVE_PROP_MATERIALS[prop.model] ?? []) materials.add(m);
  }
  const target = new URL('MaterialCollections/MaterialCollection.DeepFrontierLategame.blueprint.json', targetRoot);
  await mkdir(dirname(fileURLToPath(target)), {recursive: true});
  await writeFile(target, JSON.stringify({MaterialCollectionSpec: {CollectionId: 'IronTeeth', Materials: [...materials].sort()}},
    null, 2) + '\n');
}

// Blueprint and its exported meshes enter the active package together.
// dataRoot (a filesystem path) defaults to the active src/DeepFrontier/Data;
// a generator that writes another data root (radiation_content.mjs dataRoot)
// passes it so the meshes land beside its blueprints.
export async function applyLategame(value, id, {dataRoot, ...options} = {}) {
  const result = await lategameBlueprint(value, id, options);
  const targetRoot = dataRoot ? pathToFileURL(dataRoot.endsWith(sep) ? dataRoot : dataRoot + sep) : new URL('src/DeepFrontier/Data/', root);
  for (const resource of [result.model, result.stage]) {
    const source = new URL(`outputs/lategame-integration/Data/${resource}.timbermesh`, root);
    const target = new URL(`${resource}.timbermesh`, targetRoot);
    await mkdir(dirname(fileURLToPath(target)), {recursive: true});
    await copyFile(source, target);
  }
  await writeNativePropMaterials(targetRoot);
  return result;
}
