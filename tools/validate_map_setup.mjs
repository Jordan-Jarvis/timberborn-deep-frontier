// Static checks for the built-in new-game setup (tools/map_setup_content.mjs,
// src/DeepFrontier/Scripts/MapSetup). Usage:
//   node tools/validate_map_setup.mjs [dataRoot]
// - Configurations/DeepFrontierMapSetup.blueprint.json equals what map_setup_content.mjs derives
//   from tools/map_variants/*.json and tools/map_setup.json (no hand edits, no stale data);
// - every DeepFrontier.MapSetup.* row is in enUS.csv with that text, and no other row uses the prefix;
// - the spec records and loc keys of the C# runtime match the generated data.
// The terrain validation of every placement and the coverage of every built-in map need the game
// files: tools/prepare_deep_frontier_map.py builtin (validate_all check map-setup-terrain).
// Static evidence only: it does not establish placement, height or dialogs in game.
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {MAP_SETUP_FILES, LOC_PREFIX, TEXT_KEYS, textLocKey, csvRow, mapSetupContent} from './map_setup_content.mjs';

const root = resolve(fileURLToPath(new URL('../', import.meta.url)));
const dataRoot = process.argv[2] ? resolve(process.argv[2]) : resolve(root, 'src', 'DeepFrontier', 'Data');
const scripts = resolve(root, 'src', 'DeepFrontier', 'Scripts', 'MapSetup');
const readJson = async (path) => JSON.parse((await readFile(path, 'utf8')).replace(/^﻿/, ''));
const failures = [];
const assert = (condition, message) => { if (!condition) failures.push(message); };

const {spec, rows} = await mapSetupContent({root, dataRoot});
const written = await readJson(resolve(dataRoot, MAP_SETUP_FILES.settings));
assert(JSON.stringify(written) === JSON.stringify({BuiltinMapSetupSpec: spec}),
  `${MAP_SETUP_FILES.settings} differs from the data derived from tools/map_variants and tools/map_setup.json; regenerate (canonical generation)`);

const lines = (await readFile(resolve(dataRoot, MAP_SETUP_FILES.localization), 'utf8')).split(/\r?\n/);
const present = new Set(lines);
for (const [id, text] of rows) assert(present.has(csvRow(id, text)), `enUS.csv lacks or changed ${id}`);
const expectedIds = new Set(rows.map(([id]) => id));
for (const line of lines) {
  const id = line.split(',')[0];
  if (id.startsWith(LOC_PREFIX)) assert(expectedIds.has(id), `enUS.csv row ${id} is not generated by map_setup_content.mjs`);
}

// C# contract: MapSetupLoc constants and the spec records' [Serialize] properties.
const setupCs = await readFile(resolve(scripts, 'BuiltinMapSetup.cs'), 'utf8');
const locConstants = [...setupCs.matchAll(/public const string (\w+) = Prefix \+ "(\w+)";/g)].map((m) => [m[1], m[2]]);
const prefix = /private const string Prefix = "([^"]+)";/.exec(setupCs)?.[1];
assert(prefix === LOC_PREFIX, `MapSetupLoc.Prefix ${prefix} != ${LOC_PREFIX}`);
const csKeys = new Set(locConstants.map(([, key]) => LOC_PREFIX + key));
const textKeys = new Set(TEXT_KEYS.map(textLocKey));
for (const key of textKeys) assert(csKeys.has(key), `MapSetupLoc has no constant for ${key}`);
for (const key of csKeys) assert(textKeys.has(key), `MapSetupLoc.${key} has no text in tools/map_setup.json`);
for (const [name, key] of locConstants) assert(name === key, `MapSetupLoc.${name} names ${key}`);

const specsCs = await readFile(resolve(scripts, 'MapSetupSpecs.cs'), 'utf8');
const records = {};
for (const m of specsCs.matchAll(/internal record (\w+)[^{]*\{([\s\S]*?)\n  \}/g))
  records[m[1]] = [...m[2].matchAll(/\[Serialize\] public [\w<>]+ (\w+) \{ get; init; \}/g)].map((p) => p[1]);
const sameKeys = (record, object) => {
  const fields = records[record];
  assert(Array.isArray(fields), `MapSetupSpecs.cs has no record ${record}`);
  if (fields) assert(JSON.stringify([...fields].sort()) === JSON.stringify(Object.keys(object).sort()),
    `${record} [Serialize] properties ${fields.join(', ')} != generated keys ${Object.keys(object).join(', ')}`);
};
sameKeys('BuiltinMapSetupSpec', spec);
assert(spec.Maps.length > 0, 'no built-in map entries');
if (spec.Maps.length) {
  sameKeys('BuiltinMapSpec', spec.Maps[0]);
  const withPlacement = spec.Maps.find((m) => m.Placements.length);
  if (withPlacement) sameKeys('MapPlacementSpec', withPlacement.Placements[0]);
}

const report = {
  check: 'map-setup',
  maps: spec.Maps.map((m) => ({map: m.MapName, variant: m.VariantId, size: [m.Width, m.Height], totalHeight: m.TotalHeight,
    small: m.Small, placements: m.Placements.length, unmet: m.UnmetLocKeys.length})),
  smallMapMaxArea: spec.SmallMapMaxArea, devMaps: spec.DevMaps, rows: rows.length, failures,
};
if (failures.length) {
  console.error(`Map setup validation failed (${failures.length}):\n  ${failures.join('\n  ')}`);
  process.exit(1);
}
console.log(JSON.stringify(report));
